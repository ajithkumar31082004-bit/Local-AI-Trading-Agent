"""Data models for SQLite persistence and domain entities."""

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Optional, List, Dict, Any


class OrderSide(str, Enum):
    BUY = "BUY"
    SELL = "SELL"


class OrderType(str, Enum):
    MARKET = "MARKET"
    LIMIT = "LIMIT"


class OrderStatus(str, Enum):
    PENDING = "PENDING"
    FILLED = "FILLED"
    REJECTED = "REJECTED"
    CANCELLED = "CANCELLED"


class SignalType(str, Enum):
    BUY = "BUY"
    SELL = "SELL"
    HOLD = "HOLD"
    NO_SIGNAL = "NO_SIGNAL"


@dataclass
class TradeRecord:
    """Represents a completed or attempted trade."""
    id: Optional[int] = None
    symbol: str = ""
    side: str = OrderSide.BUY.value
    quantity: float = 0.0
    price: float = 0.0
    fee: float = 0.0
    slippage: float = 0.0
    total_cost: float = 0.0
    timestamp: str = field(default_factory=lambda: datetime.now().isoformat())
    strategy: str = "MANUAL"
    status: str = OrderStatus.FILLED.value
    notes: str = ""


@dataclass
class PositionRecord:
    """Represents an active or closed position in the portfolio."""
    id: Optional[int] = None
    symbol: str = ""
    quantity: float = 0.0
    avg_entry_price: float = 0.0
    current_price: float = 0.0
    market_value: float = 0.0
    unrealized_pnl: float = 0.0
    unrealized_pnl_pct: float = 0.0
    realized_pnl: float = 0.0
    stop_loss: Optional[float] = None
    take_profit: Optional[float] = None
    opened_at: str = field(default_factory=lambda: datetime.now().isoformat())
    updated_at: str = field(default_factory=lambda: datetime.now().isoformat())


@dataclass
class AccountSnapshot:
    """Represents the portfolio state at a given point in time."""
    timestamp: str = field(default_factory=lambda: datetime.now().isoformat())
    initial_balance: float = 100000.0
    cash_balance: float = 100000.0
    positions_value: float = 0.0
    total_equity: float = 100000.0
    unrealized_pnl: float = 0.0
    realized_pnl: float = 0.0
    total_fees_paid: float = 0.0
    drawdown_pct: float = 0.0
    peak_equity: float = 100000.0
    open_positions_count: int = 0


@dataclass
class StrategySignal:
    """Represents a deterministic signal generated by a trading strategy."""
    symbol: str
    strategy_name: str
    signal: SignalType
    strength: float = 1.0  # 0.0 to 1.0
    price: float = 0.0
    timestamp: str = field(default_factory=lambda: datetime.now().isoformat())
    indicators: Dict[str, Any] = field(default_factory=dict)
    rationale: str = ""
    invalidation_criteria: str = ""
    suggested_stop_loss: Optional[float] = None
    suggested_take_profit: Optional[float] = None
